-- Shared PostgreSQL schema. All ownership and relations include the tenant key.
CREATE TABLE users (user_hash TEXT PRIMARY KEY, created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'));
CREATE TABLE user_meta (
    user_hash TEXT NOT NULL REFERENCES users(user_hash) ON DELETE CASCADE,
    key TEXT NOT NULL,
    value TEXT NOT NULL,
    PRIMARY KEY (user_hash, key)
);

CREATE TABLE folders (
    user_hash TEXT NOT NULL REFERENCES users(user_hash) ON DELETE CASCADE,
    name TEXT NOT NULL,
    delimiter TEXT,
    parent TEXT,
    flags TEXT NOT NULL DEFAULT '',
    is_subscribed BIGINT NOT NULL DEFAULT 1 CHECK (is_subscribed IN (0, 1)),
    total_count BIGINT NOT NULL DEFAULT 0,
    unread_count BIGINT NOT NULL DEFAULT 0,
    uid_validity BIGINT NOT NULL DEFAULT 0,
    updated_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    messages_updated_at TEXT,
    highest_modseq NUMERIC(20,0) NOT NULL DEFAULT '0' CHECK (highest_modseq >= 0 AND highest_modseq <= 18446744073709551615),
    PRIMARY KEY (user_hash, name)
);

CREATE TABLE messages (
    user_hash TEXT NOT NULL REFERENCES users(user_hash) ON DELETE CASCADE,
    uid BIGINT NOT NULL,
    folder TEXT NOT NULL,
    message_id TEXT,
    in_reply_to TEXT,
    subject TEXT NOT NULL DEFAULT '',
    from_address TEXT NOT NULL DEFAULT '',
    from_name TEXT NOT NULL DEFAULT '',
    to_addresses TEXT NOT NULL DEFAULT '',
    cc_addresses TEXT NOT NULL DEFAULT '',
    date TEXT NOT NULL,
    flags TEXT NOT NULL DEFAULT '',
    size BIGINT NOT NULL DEFAULT 0,
    has_attachments BIGINT NOT NULL DEFAULT 0 CHECK (has_attachments IN (0, 1)),
    snippet TEXT NOT NULL DEFAULT '',
    body_cached BIGINT NOT NULL DEFAULT 0 CHECK (body_cached IN (0, 1)),
    body_html TEXT,
    body_text TEXT,
    references_header TEXT,
    date_epoch BIGINT NOT NULL DEFAULT 0,
    attachments_json TEXT,
    raw_headers TEXT,
    reaction TEXT,
    email_theme BIGINT,
    PRIMARY KEY (user_hash, uid, folder),
    FOREIGN KEY (user_hash, folder) REFERENCES folders(user_hash, name) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE drafts (
    user_hash TEXT NOT NULL REFERENCES users(user_hash) ON DELETE CASCADE,
    id TEXT NOT NULL,
    to_addresses TEXT NOT NULL DEFAULT '',
    cc_addresses TEXT NOT NULL DEFAULT '',
    bcc_addresses TEXT NOT NULL DEFAULT '',
    subject TEXT NOT NULL DEFAULT '',
    text_body TEXT NOT NULL DEFAULT '',
    html_body TEXT,
    in_reply_to TEXT,
    references_header TEXT,
    created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    updated_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    PRIMARY KEY (user_hash, id)
);

CREATE TABLE draft_attachments (
    user_hash TEXT NOT NULL REFERENCES users(user_hash) ON DELETE CASCADE,
    id TEXT NOT NULL,
    draft_id TEXT NOT NULL,
    filename TEXT NOT NULL,
    content_type TEXT NOT NULL,
    size BIGINT NOT NULL,
    file_path TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    PRIMARY KEY (user_hash, id),
    FOREIGN KEY (user_hash, draft_id) REFERENCES drafts(user_hash, id) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE contacts (
    user_hash TEXT NOT NULL REFERENCES users(user_hash) ON DELETE CASCADE,
    id TEXT NOT NULL,
    email TEXT NOT NULL,
    name TEXT NOT NULL DEFAULT '',
    company TEXT NOT NULL DEFAULT '',
    notes TEXT NOT NULL DEFAULT '',
    is_favorite BIGINT NOT NULL DEFAULT 0 CHECK (is_favorite IN (0, 1)),
    last_contacted TEXT,
    contact_count BIGINT NOT NULL DEFAULT 0,
    source TEXT NOT NULL DEFAULT 'manual',
    created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    updated_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    PRIMARY KEY (user_hash, id),
    UNIQUE (user_hash, email)
);

CREATE TABLE identities (
    user_hash TEXT NOT NULL REFERENCES users(user_hash) ON DELETE CASCADE,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    display_name TEXT NOT NULL DEFAULT '',
    email TEXT NOT NULL,
    signature_html TEXT NOT NULL DEFAULT '',
    is_default BIGINT NOT NULL DEFAULT 0 CHECK (is_default IN (0, 1)),
    created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    updated_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    PRIMARY KEY (user_hash, id)
);

CREATE TABLE notification_preferences (
    user_hash TEXT NOT NULL REFERENCES users(user_hash) ON DELETE CASCADE,
    id BIGINT NOT NULL DEFAULT 1 CHECK (id = 1),
    enabled BIGINT NOT NULL DEFAULT 1 CHECK (enabled IN (0, 1)),
    sound BIGINT NOT NULL DEFAULT 0 CHECK (sound IN (0, 1)),
    folders TEXT NOT NULL DEFAULT '["INBOX"]',
    updated_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    PRIMARY KEY (user_hash, id),
    UNIQUE (user_hash)
);

CREATE TABLE contact_groups (
    user_hash TEXT NOT NULL REFERENCES users(user_hash) ON DELETE CASCADE,
    id TEXT NOT NULL,
    name TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    updated_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    PRIMARY KEY (user_hash, id),
    UNIQUE (user_hash, name)
);

CREATE TABLE contact_group_members (
    user_hash TEXT NOT NULL REFERENCES users(user_hash) ON DELETE CASCADE,
    group_id TEXT NOT NULL,
    contact_id TEXT NOT NULL,
    PRIMARY KEY (user_hash, group_id, contact_id),
    FOREIGN KEY (user_hash, group_id) REFERENCES contact_groups(user_hash, id) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (user_hash, contact_id) REFERENCES contacts(user_hash, id) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE tags (
    user_hash TEXT NOT NULL REFERENCES users(user_hash) ON DELETE CASCADE,
    id TEXT NOT NULL,
    name TEXT NOT NULL,
    color TEXT NOT NULL DEFAULT '#6b7280',
    created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    updated_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    PRIMARY KEY (user_hash, id),
    UNIQUE (user_hash, name)
);

CREATE TABLE message_tags (
    user_hash TEXT NOT NULL REFERENCES users(user_hash) ON DELETE CASCADE,
    tag_id TEXT NOT NULL,
    message_uid BIGINT NOT NULL,
    message_folder TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    PRIMARY KEY (user_hash, tag_id, message_uid, message_folder),
    FOREIGN KEY (user_hash, tag_id) REFERENCES tags(user_hash, id) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (user_hash, message_uid, message_folder) REFERENCES messages(user_hash, uid, folder) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE display_preferences (
    user_hash TEXT NOT NULL REFERENCES users(user_hash) ON DELETE CASCADE,
    id BIGINT NOT NULL DEFAULT 1 CHECK (id = 1),
    density TEXT NOT NULL DEFAULT 'comfortable',
    theme TEXT NOT NULL DEFAULT 'system',
    language TEXT NOT NULL DEFAULT 'en',
    updated_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    compose_format TEXT NOT NULL DEFAULT 'html',
    deep_index BIGINT NOT NULL DEFAULT 0 CHECK (deep_index IN (0, 1)),
    animation_mode TEXT,
    PRIMARY KEY (user_hash, id),
    UNIQUE (user_hash)
);

CREATE TABLE calendar_events (
    user_hash TEXT NOT NULL REFERENCES users(user_hash) ON DELETE CASCADE,
    id TEXT NOT NULL,
    title TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    location TEXT NOT NULL DEFAULT '',
    start_time TEXT NOT NULL,
    end_time TEXT NOT NULL,
    all_day BIGINT NOT NULL DEFAULT 0 CHECK (all_day IN (0, 1)),
    recurrence_rule TEXT,
    attendees TEXT NOT NULL DEFAULT '[]',
    organizer TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'confirmed',
    source TEXT NOT NULL DEFAULT 'manual',
    source_uid TEXT,
    source_message_uid BIGINT,
    source_message_folder TEXT,
    meeting_url TEXT,
    color TEXT,
    reminder_minutes BIGINT,
    created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    updated_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    PRIMARY KEY (user_hash, id)
);

CREATE TABLE calendar_settings (
    user_hash TEXT NOT NULL REFERENCES users(user_hash) ON DELETE CASCADE,
    id BIGINT NOT NULL DEFAULT 1 CHECK (id = 1),
    default_view TEXT NOT NULL DEFAULT 'month',
    week_starts_on BIGINT NOT NULL DEFAULT 0,
    working_hours_start TEXT NOT NULL DEFAULT '09:00',
    working_hours_end TEXT NOT NULL DEFAULT '17:00',
    time_format TEXT NOT NULL DEFAULT '12h',
    zoom_link TEXT NOT NULL DEFAULT '',
    teams_link TEXT NOT NULL DEFAULT '',
    meet_link TEXT NOT NULL DEFAULT '',
    caldav_url TEXT NOT NULL DEFAULT '',
    caldav_username TEXT NOT NULL DEFAULT '',
    caldav_password TEXT NOT NULL DEFAULT '',
    caldav_enabled BIGINT NOT NULL DEFAULT 0 CHECK (caldav_enabled IN (0, 1)),
    updated_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    PRIMARY KEY (user_hash, id),
    UNIQUE (user_hash)
);

CREATE TABLE meeting_templates (
    user_hash TEXT NOT NULL REFERENCES users(user_hash) ON DELETE CASCADE,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name TEXT NOT NULL,
    url_template TEXT NOT NULL,
    icon TEXT NOT NULL DEFAULT '',
    is_default BIGINT NOT NULL DEFAULT 0 CHECK (is_default IN (0, 1)),
    created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    PRIMARY KEY (user_hash, id)
);

CREATE TABLE known_addresses (
    user_hash TEXT NOT NULL REFERENCES users(user_hash) ON DELETE CASCADE,
    email TEXT NOT NULL,
    name TEXT NOT NULL DEFAULT '',
    PRIMARY KEY (user_hash, email)
);

CREATE INDEX idx_messages_lookup_0 ON messages(user_hash, folder, date_epoch DESC);
CREATE INDEX idx_messages_lookup_1 ON messages(user_hash, message_id);
CREATE INDEX idx_messages_lookup_2 ON messages(user_hash, in_reply_to);
CREATE INDEX idx_contacts_lookup_0 ON contacts(user_hash, name);
CREATE INDEX idx_contacts_lookup_1 ON contacts(user_hash, last_contacted DESC);
CREATE INDEX idx_contacts_lookup_2 ON contacts(user_hash, contact_count DESC);
CREATE INDEX idx_known_addresses_lookup_0 ON known_addresses(user_hash, name);
CREATE INDEX idx_calendar_events_lookup_0 ON calendar_events(user_hash, start_time, end_time);
CREATE INDEX idx_calendar_events_lookup_1 ON calendar_events(user_hash, source_uid);
CREATE INDEX idx_contact_group_members_lookup_0 ON contact_group_members(user_hash, contact_id);
CREATE INDEX idx_message_tags_lookup_0 ON message_tags(user_hash, message_uid, message_folder);
CREATE INDEX idx_message_tags_lookup_1 ON message_tags(user_hash, tag_id);
